#!/usr/bin/env node
// Memory bank indexer for Ówàńbè.
//
//   node scripts/memory-bank.mjs check    verify the memory bank matches the code (CI)
//   node scripts/memory-bank.mjs update   refresh the file map + fingerprints after you've
//                                         reviewed/updated the memory docs for your change
//   node scripts/memory-bank.mjs where <path>   which memory doc(s) describe a file
//
// What it guarantees:
//   * every tracked source file appears in memory-bank/03-codebase-map.md with a real description
//   * no deleted file is still described
//   * memory-bank/index.json fingerprints match the code, so a change that skipped the
//     memory-bank protocol fails `npm run ci` and names the docs that need review
// No dependencies; Node 18+.

import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MB = path.join(ROOT, "memory-bank");
const MAP_FILE = path.join(MB, "03-codebase-map.md");
const INDEX_FILE = path.join(MB, "index.json");
const MAP_START = "<!-- map:start -->";
const MAP_END = "<!-- map:end -->";
const TODO = "TODO: describe";

// Paths that are not indexed (generated, vendored, binary assets or owned by another system).
const IGNORE = [
  /^\.git\//, /(^|\/)node_modules\//, /(^|\/)\.expo\//, /^\.tanstack\//, /^\.output\//, /^\.nitro\//, /^\.vinxi\//, /^\.wrangler\//, /^\.lovable\//,
  /^dist\//, /^coverage\//, /^Claude outputs\//,
  /^memory-bank\//, /^blueprint\//, /^owanbe-brand-kit\//, /^public\/(images|icons)\//,
  /^src\/components\/ui\//, /^drizzle\//, /^src\/routeTree\.gen\.ts$/,
  /(^|\/)package-lock\.json$/, /^bun\.lock$/, /^publish-to-github\.ps1$/,
  /\.(png|jpe?g|webp|ico|pdf|gif)$/i,
  /^\.env(\..*)?$/, /\.local$/, /\.tsbuildinfo$/,
];
const ALWAYS_KEEP = [/^\.env\.example$/];

function walk(dir = ROOT, out = []) {
  for (const name of readdirSync(dir)) {
    const abs = path.join(dir, name);
    const rel = path.relative(ROOT, abs).split(path.sep).join("/");
    const isDir = statSync(abs).isDirectory();
    const probe = isDir ? `${rel}/` : rel;
    if (!ALWAYS_KEEP.some((r) => r.test(rel)) && IGNORE.some((r) => r.test(probe))) continue;
    if (isDir) walk(abs, out);
    else out.push(rel);
  }
  return out.sort();
}

const fingerprint = (rel) =>
  createHash("sha256").update(readFileSync(path.join(ROOT, rel), "utf8").replace(/\r\n/g, "\n")).digest("hex").slice(0, 16);

function readIndex() {
  return JSON.parse(readFileSync(INDEX_FILE, "utf8"));
}

/** Memory docs responsible for a path, from index.json "coverage" (first match wins per rule order, all matches returned). */
function docsFor(rel, coverage) {
  const hits = coverage.filter((c) => new RegExp(c.pattern).test(rel)).map((c) => c.docs).flat();
  return [...new Set(hits.length ? hits : ["03-codebase-map.md"])];
}

function parseMap() {
  const text = readFileSync(MAP_FILE, "utf8");
  const start = text.indexOf(MAP_START);
  const end = text.indexOf(MAP_END);
  if (start < 0 || end < 0) throw new Error(`03-codebase-map.md must contain ${MAP_START} … ${MAP_END}`);
  const rows = new Map();
  for (const line of text.slice(start, end).split("\n")) {
    const m = line.match(/^\|\s*`([^`]+)`\s*\|\s*(.*?)\s*\|$/);
    if (m) rows.set(m[1], m[2]);
  }
  return { text, start, end, rows };
}

function renderMap(files, rows) {
  const groups = new Map();
  for (const f of files) {
    const top = f.includes("/") ? f.split("/").slice(0, f.startsWith("src/") || f.startsWith("supabase/") ? 2 : 1).join("/") + "/" : "(root)";
    if (!groups.has(top)) groups.set(top, []);
    groups.get(top).push(f);
  }
  let out = `${MAP_START}\n<!-- Generated by \`bun run memory:update\` (or \`node scripts/memory-bank.mjs update\`). Edit descriptions in place; rows are added/removed automatically. -->\n`;
  for (const [group, list] of groups) {
    out += `\n#### ${group}\n\n| File | Purpose |\n|---|---|\n`;
    for (const f of list) out += `| \`${f}\` | ${rows.get(f) || TODO} |\n`;
  }
  return out + `\n${MAP_END}`;
}

function check() {
  const index = readIndex();
  const files = walk();
  const { rows } = parseMap();
  const problems = [];
  const review = new Map();

  for (const f of files) {
    if (!rows.has(f)) problems.push(`not in codebase map: ${f}`);
    else if (!rows.get(f) || rows.get(f) === TODO) problems.push(`missing description: ${f}`);
    const known = index.files[f];
    if (!known) problems.push(`not fingerprinted (new file): ${f}`);
    else if (known !== fingerprint(f)) problems.push(`changed since last memory update: ${f}`);
    if (!known || known !== fingerprint(f)) for (const d of docsFor(f, index.coverage)) review.set(d, [...(review.get(d) ?? []), f]);
  }
  for (const f of rows.keys()) if (!files.includes(f)) problems.push(`described but deleted: ${f}`);
  for (const f of Object.keys(index.files)) if (!files.includes(f)) {
    problems.push(`fingerprinted but deleted: ${f}`);
    for (const d of docsFor(f, index.coverage)) review.set(d, [...(review.get(d) ?? []), f]);
  }
  for (const doc of index.docs.map((d) => d.file)) if (!existsSync(path.join(MB, doc))) problems.push(`index lists missing doc: ${doc}`);

  if (problems.length) {
    console.error(`✗ memory bank is out of date (${problems.length} issue${problems.length > 1 ? "s" : ""}):`);
    for (const p of problems) console.error(`  - ${p}`);
    if (review.size) {
      console.error("\nReview and update these memory docs, then run `npm run memory:update`:");
      for (const [doc, list] of review) console.error(`  memory-bank/${doc}  ← ${list.join(", ")}`);
    }
    process.exit(1);
  }
  console.log(`✓ memory bank current: ${files.length} files indexed, ${index.docs.length} docs`);
}

function update() {
  const index = readIndex();
  const files = walk();
  const { text, start, end, rows } = parseMap();
  writeFileSync(MAP_FILE, text.slice(0, start) + renderMap(files, rows) + text.slice(end + MAP_END.length));
  index.files = Object.fromEntries(files.map((f) => [f, fingerprint(f)]));
  index.updatedAt = new Date().toISOString();
  writeFileSync(INDEX_FILE, JSON.stringify(index, null, 2) + "\n");
  const todo = files.filter((f) => !rows.get(f) || rows.get(f) === TODO);
  console.log(`updated index.json (${files.length} files) and 03-codebase-map.md`);
  if (todo.length) {
    console.log(`\nDescribe these new files in memory-bank/03-codebase-map.md (replace "${TODO}"):`);
    for (const f of todo) console.log(`  - ${f}`);
    process.exitCode = 1;
  }
}

function where(rel) {
  const index = readIndex();
  const norm = rel.replace(/\\/g, "/").replace(/^\.\//, "");
  console.log(`${norm} → ${docsFor(norm, index.coverage).map((d) => `memory-bank/${d}`).join(", ")}`);
  const desc = parseMap().rows.get(norm);
  if (desc) console.log(`  ${desc}`);
}

const [cmd, arg] = process.argv.slice(2);
if (cmd === "check") check();
else if (cmd === "update") update();
else if (cmd === "where" && arg) where(arg);
else {
  console.log("usage: node scripts/memory-bank.mjs <check|update|where <path>>");
  process.exit(2);
}
